import 'package:flutter_test/flutter_test.dart';
import 'package:devorbit_mobile/core/security/e2e_session.dart';

void main() {
  test('FlutterE2ESession encrypts and decrypts with directional keys and AAD', () async {
    final session = await FlutterE2ESession.create(
      sessionId: 'sess-unit-01',
      deviceId: 'dev-unit-01',
      masterSecret: 'devorbit-test-secret-32-bytes-long!',
    );

    const plainText = '{"v":"1.2","request_id":"req_1","method":"GET","path":"/api/v1/health"}';
    const seqNum = 1;
    final timestamp = DateTime.now().microsecondsSinceEpoch;

    // Encrypt client-to-host
    final encryptedHex = await session.encrypt(
      direction: Direction.clientToHost,
      plainText: plainText,
      seqNum: seqNum,
      timestamp: timestamp,
    );

    expect(encryptedHex.length, greaterThan(plainText.length));

    // Decrypt client-to-host
    final decryptedText = await session.decrypt(
      direction: Direction.clientToHost,
      cipherTextHex: encryptedHex,
      seqNum: seqNum,
      timestamp: timestamp,
    );

    expect(decryptedText, equals(plainText));
  });

  test('FlutterE2ESession Bidirectional Cross-Language Go <-> Dart Interoperability Vector', () async {
    // Deterministic Shared Vector Specification
    const masterSecret = 'devorbit-shared-test-secret-32b!';
    const sessionId = 'sess-interop-v1';
    const deviceId = 'dev-interop-phone-01';
    const seqNum = 42;
    const timestamp = 1700000000123456;

    const expectedClientKeyHex = '25a199210d6e60362d82f69a0aa08e78f3922bb87911e366706bb497058b6617';
    const expectedHostKeyHex = '8e1e0dc31889cb5ca10b909554107269fd6c9ce6afe8ba1712c67819d9551ab3';
    const expectedAADHex = '736573732d696e7465726f702d76313a6465762d696e7465726f702d70686f6e652d30313a000000000000002a00060a2418202240';

    // Vector 2: Host -> Client (Generated by Go with fixed nonce, decrypted by Dart)
    const hostExpectedPlaintext = '{"v":"1.2","session_id":"sess-interop-v1","request_id":"req_client_001","status_code":200,"body":"{\\"content\\":\\"apply plugin: \'com.android.application\'\\"}"}';
    const goGeneratedCiphertextHex = '1112131415161718191a1b1cd48e87be1e28b4f0662ec7e49d7a862b72daae1339dd37f793c9f63c272598e3f256f17f49ec974ce18812cded6170fe12ec53c1a7286a831a9e8be1b51e097b9b3b1e46e138ba76143d135470c36939b8e238014d27b6b5f9bdc6c7d1d6b4eedcf4a133c7e339e66971bc33c2b74169ef4b69844bf39c2706dc031aef9f3d3a48e3636d8913e7af2d38133867096305511d53bc342c11e94c7aceeaa2d6ac33904b9cf56acc8cbd6356515629';

    // Vector 1: Client -> Host (Generated by Dart with fixed nonce, decrypted by Go)
    const clientExpectedPlaintext = '{"v":"1.2","request_id":"req_client_001","method":"POST","path":"/api/v1/files/read","body":"{\\"path\\":\\"app/build.gradle\\"}"}';
    const dartGeneratedCiphertextHex = '0102030405060708090a0b0c6e4c90ef22a7ed9d869920aecbcf68d81efbbcfc0b8e12644bf143b3df4b1cdc19cad1e173bcfec738fa2fb268a3471260251de941f504d8c3109756cc3330ae5829b62d1ab33b83801af34f22731c16eafb7ba0366c4450aca78ced94bc4234cb59089e582739a236b951b7cd2f640d4e9db0c42e9abafa157c153537d3ac0b9e5c68f4ca1520925a6a5ba4966d';

    // 1. Requirement 2: Dart must derive and compare both directional keys against fixed expected values
    final session = await FlutterE2ESession.create(
      sessionId: sessionId,
      deviceId: deviceId,
      masterSecret: masterSecret,
    );

    final clientKeyBytes = await session.clientToHostKey.extractBytes();
    final hostKeyBytes = await session.hostToClientKey.extractBytes();

    final actualClientKeyHex = clientKeyBytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
    final actualHostKeyHex = hostKeyBytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();

    expect(actualClientKeyHex, equals(expectedClientKeyHex));
    expect(actualHostKeyHex, equals(expectedHostKeyHex));

    // 2. Requirement 5: Both implementations must verify the same AAD and metadata
    final aadBytes = session.constructAAD(seqNum, timestamp);
    final actualAADHex = aadBytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
    expect(actualAADHex, equals(expectedAADHex));

    // 3. Requirement 4: Dart must decrypt a ciphertext generated by Go
    final decryptedFromGo = await session.decrypt(
      direction: Direction.hostToClient,
      cipherTextHex: goGeneratedCiphertextHex,
      seqNum: seqNum,
      timestamp: timestamp,
    );
    expect(decryptedFromGo, equals(hostExpectedPlaintext));

    // Dart also verifies client-to-host decryption of Vector 1
    final decryptedClientVec = await session.decrypt(
      direction: Direction.clientToHost,
      cipherTextHex: dartGeneratedCiphertextHex,
      seqNum: seqNum,
      timestamp: timestamp,
    );
    expect(decryptedClientVec, equals(clientExpectedPlaintext));

    // 4. Requirement 7: Verify directional key separation
    // Host-to-client ciphertext must not decrypt using client-to-host key
    expect(
      () async => await session.decrypt(
        direction: Direction.clientToHost,
        cipherTextHex: goGeneratedCiphertextHex,
        seqNum: seqNum,
        timestamp: timestamp,
      ),
      throwsA(anything),
    );

    // 5. Requirement 6: Reject modified ciphertext, authentication tags, AAD, sequence numbers, timestamps
    // Modified ciphertext byte
    final tamperedCipher = '${goGeneratedCiphertextHex.substring(0, 40)}ff${goGeneratedCiphertextHex.substring(42)}';
    expect(
      () async => await session.decrypt(
        direction: Direction.hostToClient,
        cipherTextHex: tamperedCipher,
        seqNum: seqNum,
        timestamp: timestamp,
      ),
      throwsA(anything),
    );

    // Modified authentication tag byte
    final tamperedTag = '${goGeneratedCiphertextHex.substring(0, goGeneratedCiphertextHex.length - 2)}00';
    expect(
      () async => await session.decrypt(
        direction: Direction.hostToClient,
        cipherTextHex: tamperedTag,
        seqNum: seqNum,
        timestamp: timestamp,
      ),
      throwsA(anything),
    );

    // Modified sequence number (AAD mismatch)
    expect(
      () async => await session.decrypt(
        direction: Direction.hostToClient,
        cipherTextHex: goGeneratedCiphertextHex,
        seqNum: seqNum + 1,
        timestamp: timestamp,
      ),
      throwsA(anything),
    );

    // Modified timestamp (AAD mismatch)
    expect(
      () async => await session.decrypt(
        direction: Direction.hostToClient,
        cipherTextHex: goGeneratedCiphertextHex,
        seqNum: seqNum,
        timestamp: timestamp + 1000,
      ),
      throwsA(anything),
    );
  });

  test('FlutterE2ESession deriveHttpAuthKey and computeHttpRequestMac match Go vectors exactly', () async {
    const masterSecret = 'devorbit-shared-test-secret-32b!';
    const sessionId = 'sess-interop-v1';
    const deviceId = 'dev-interop-phone-01';
    const expectedAuthKeyHex = '0a41360b559c8c0122c04cf156b43903209c1b0c1bd8ac9e61f7501e5b071a90';
    const expectedMacHex = '7a1627cea91b8abcb68da5ffef7ff1afa9017527a6da2f870abcb92c70459d37';

    final authKey = await FlutterE2ESession.deriveHttpAuthKey(
      sessionId: sessionId,
      deviceId: deviceId,
      masterSecret: masterSecret,
    );
    final actualAuthKeyHex = authKey.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
    expect(actualAuthKeyHex, equals(expectedAuthKeyHex));

    final actualMacHex = FlutterE2ESession.computeHttpRequestMac(
      authKey: authKey,
      method: 'POST',
      requestUri: '/api/v1/e2e',
      sessionId: sessionId,
      deviceId: deviceId,
      timestamp: '1700000000123456',
      nonce: 'nonce-interop-0001',
      bodySha256Hex: 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855',
    );
    expect(actualMacHex, equals(expectedMacHex));
  });
}
