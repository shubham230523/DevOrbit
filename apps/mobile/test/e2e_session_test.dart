import 'package:flutter_test/flutter_test.dart';
import 'package:devorbit_mobile/core/security/e2e_session.dart';

void main() {
  test('FlutterE2ESession encrypts and decrypts with directional keys and AAD', () async {
    final session = await FlutterE2ESession.create(
      sessionId: 'sess-test-01',
      deviceId: 'dev-phone-01',
      masterSecret: 'devorbit-master-secret-key-32b!',
    );

    const plainText = '{"v":"1.2","request_id":"req_1","method":"GET","path":"/api/v1/health"}';
    const seqNum = 1;
    final timestamp = DateTime.now().microsecondsSinceEpoch;

    // Encrypt client-to-host
    final encryptedHex = await session.encrypt(
      direction: Direction.clientToHost,
      plainText: plainText,
      seqNum: seqNum,
      timestamp: timestamp,
    );

    expect(encryptedHex.length, greaterThan(plainText.length));

    // Decrypt client-to-host
    final decryptedText = await session.decrypt(
      direction: Direction.clientToHost,
      cipherTextHex: encryptedHex,
      seqNum: seqNum,
      timestamp: timestamp,
    );

    expect(decryptedText, equals(plainText));
  });

  test('FlutterE2ESession Cross-Language Go <-> Dart Interoperability Vector', () async {
    const masterSecret = 'devorbit-test-master-secret-32b!';
    const sessionId = 'sess-interop-001';
    const deviceId = 'dev-interop-001';
    const expectedClientKeyHex = '5ed976ff0530f1b790232c5a9540bd6601d64a83c19a3ecaa2d551fff1e64b3b';
    const expectedHostKeyHex = '71358a2f7efc9df13996d90a12544ee3934309e5a108ca9a1bc8c2ed7dabf7a4';
    const expectedAADHex = '736573732d696e7465726f702d3030313a6465762d696e7465726f702d3030313a00000000000000010000018bcfe56800';
    const goGeneratedCiphertextHex = '000000000000000000000000bcb7de422ccd316c5fcc3d55ce2dc4dcc78efafccb36e45b3307c7a9c7b67c6b0eb5bb0972cc626c7c70d6551952db4e7cf82ac503b18bcfbecc547dcb871fd35e86600d944d9818eff5bc9ffd5ece3f4f810bfa396554005a61cec378bedbe4ec';

    final session = await FlutterE2ESession.create(
      sessionId: sessionId,
      deviceId: deviceId,
      masterSecret: masterSecret,
    );

    final clientKeyBytes = await session.clientToHostKey.extractBytes();
    final hostKeyBytes = await session.hostToClientKey.extractBytes();

    final actualClientKeyHex = clientKeyBytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
    final actualHostKeyHex = hostKeyBytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();

    expect(actualClientKeyHex, equals(expectedClientKeyHex));
    expect(actualHostKeyHex, equals(expectedHostKeyHex));

    final aadBytes = session.constructAAD(1, 1700000000000);
    final actualAADHex = aadBytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
    expect(actualAADHex, equals(expectedAADHex));

    // Dart decrypts ciphertext generated by Go
    final decryptedTextFromGo = await session.decrypt(
      direction: Direction.clientToHost,
      cipherTextHex: goGeneratedCiphertextHex,
      seqNum: 1,
      timestamp: 1700000000000,
    );

    expect(decryptedTextFromGo, equals('{"v":"1.2","request_id":"req_interop_001","method":"GET","path":"/api/v1/health"}'));
  });
}
