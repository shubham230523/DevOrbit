func TestE2ESession_HKDFKeyDerivationAndDirectionalSeparation(t *testing.T) {
	session, err := NewE2ESession("sess-100", "device-phone-01", "shared-master-secret-32-bytes", 1*time.Hour)
	if err != nil {
		t.Fatalf("Failed to initialize E2E session: %v", err)
	}

	if bytes.Equal(session.ClientToHostKey, session.HostToClientKey) {
		t.Fatalf("Security failure! Client-to-Host key must be distinct from Host-to-Client key")
	}

	plain := []byte("Sensitive Code Edit Command")
	seqNum := int64(1)
	ts := time.Now().UnixNano()

	cipherHex, err := session.Encrypt(DirClientToHost, plain, seqNum, ts)
	if err != nil {
		t.Fatalf("Failed to encrypt client payload: %v", err)
	}

	decrypted, err := session.Decrypt(DirClientToHost, cipherHex, seqNum, ts)
	if err != nil {
		t.Fatalf("Failed to decrypt payload: %v", err)
	}

	if string(decrypted) != string(plain) {
		t.Errorf("Decrypted text mismatch")
	}
}

// TestE2ESession_BidirectionalCrossLanguageInteroperability verifies complete bidirectional
// cryptographic interoperability between Go and Dart using deterministic shared test vectors.
func TestE2ESession_BidirectionalCrossLanguageInteroperability(t *testing.T) {
	// Deterministic Shared Vector Specification
	const masterSecret = "devorbit-shared-test-secret-32b!"
	const sessionID = "sess-interop-v1"
	const deviceID = "dev-interop-phone-01"
	const seqNum = int64(42)
	const timestamp = int64(1700000000123456)

	const expectedClientKeyHex = "25a199210d6e60362d82f69a0aa08e78f3922bb87911e366706bb497058b6617"
	const expectedHostKeyHex = "8e1e0dc31889cb5ca10b909554107269fd6c9ce6afe8ba1712c67819d9551ab3"
	const expectedAADHex = "736573732d696e7465726f702d76313a6465762d696e7465726f702d70686f6e652d30313a000000000000002a00060a2418202240"

	// Vector 1: Client -> Host (Generated by Dart with fixed nonce, decrypted by Go)
	const clientExpectedPlaintext = `{"v":"1.2","request_id":"req_client_001","method":"POST","path":"/api/v1/files/read","body":"{\"path\":\"app/build.gradle\"}"}`
	const dartGeneratedCiphertextHex = "0102030405060708090a0b0c6e4c90ef22a7ed9d869920aecbcf68d81efbbcfc0b8e12644bf143b3df4b1cdc19cad1e173bcfec738fa2fb268a3471260251de941f504d8c3109756cc3330ae5829b62d1ab33b83801af34f22731c16eafb7ba0366c4450aca78ced94bc4234cb59089e582739a236b951b7cd2f640d4e9db0c42e9abafa157c153537d3ac0b9e5c68f4ca1520925a6a5ba4966d"

	// Vector 2: Host -> Client (Generated by Go with fixed nonce, decrypted by Dart)
	const hostExpectedPlaintext = `{"v":"1.2","session_id":"sess-interop-v1","request_id":"req_client_001","status_code":200,"body":"{\"content\":\"apply plugin: 'com.android.application'\"}"}`
	const goGeneratedCiphertextHex = "1112131415161718191a1b1cd48e87be1e28b4f0662ec7e49d7a862b72daae1339dd37f793c9f63c272598e3f256f17f49ec974ce18812cded6170fe12ec53c1a7286a831a9e8be1b51e097b9b3b1e46e138ba76143d135470c36939b8e238014d27b6b5f9bdc6c7d1d6b4eedcf4a133c7e339e66971bc33c2b74169ef4b69844bf39c2706dc031aef9f3d3a48e3636d8913e7af2d38133867096305511d53bc342c11e94c7aceeaa2d6ac33904b9cf56acc8cbd6356515629"

	// 1. Requirement 1: Go must derive and compare both directional keys against fixed expected values
	cKey, hKey, err := DeriveDirectionalKeys(masterSecret, sessionID, deviceID)
	if err != nil {
		t.Fatalf("DeriveDirectionalKeys failed: %v", err)
	}

	actualCKeyHex := hex.EncodeToString(cKey)
	actualHKeyHex := hex.EncodeToString(hKey)

	if actualCKeyHex != expectedClientKeyHex {
		t.Errorf("ClientToHostKey mismatch!\nExpected: %s\nActual:   %s", expectedClientKeyHex, actualCKeyHex)
	}
	if actualHKeyHex != expectedHostKeyHex {
		t.Errorf("HostToClientKey mismatch!\nExpected: %s\nActual:   %s", expectedHostKeyHex, actualHKeyHex)
	}

	// 2. Requirement 5: Verify AAD construction
	session, err := NewE2ESession(sessionID, deviceID, masterSecret, 1*time.Hour)
	if err != nil {
		t.Fatalf("NewE2ESession failed: %v", err)
	}

	aad := session.ConstructAAD(seqNum, timestamp)
	actualAADHex := hex.EncodeToString(aad)
	if actualAADHex != expectedAADHex {
		t.Errorf("ConstructAAD mismatch!\nExpected: %s\nActual:   %s", expectedAADHex, actualAADHex)
	}

	// 3. Requirement 3: Go must decrypt ciphertext generated by Dart
	decryptedFromDart, err := session.Decrypt(DirClientToHost, dartGeneratedCiphertextHex, seqNum, timestamp)
	if err != nil {
		t.Fatalf("Go failed to decrypt Dart-generated ciphertext: %v", err)
	}
	if string(decryptedFromDart) != clientExpectedPlaintext {
		t.Fatalf("Decrypted plaintext mismatch!\nExpected: %s\nActual:   %s", clientExpectedPlaintext, string(decryptedFromDart))
	}

	// 4. Requirement 7: Directional key separation
	// A client-to-host ciphertext must NOT decrypt using host-to-client key
	separateSession, _ := NewE2ESession(sessionID, deviceID, masterSecret, 1*time.Hour)
	_, err = separateSession.Decrypt(DirHostToClient, dartGeneratedCiphertextHex, seqNum+1, timestamp)
	if err == nil {
		t.Errorf("Security failure! Client-to-host ciphertext decrypted with host-to-client key")
	}

	// 5. Requirement 6: Reject modified ciphertext
	tamperedCipher := []byte(dartGeneratedCiphertextHex)
	tamperedCipher[30] = 'f' // flip a character in ciphertext
	_, err = separateSession.Decrypt(DirClientToHost, string(tamperedCipher), seqNum+2, timestamp)
	if err == nil {
		t.Errorf("Security failure! Decryption succeeded despite modified ciphertext bytes")
	}

	// Reject modified authentication tag
	tamperedTag := []byte(dartGeneratedCiphertextHex)
	tamperedTag[len(tamperedTag)-2] = '0'
	_, err = separateSession.Decrypt(DirClientToHost, string(tamperedTag), seqNum+3, timestamp)
	if err == nil {
		t.Errorf("Security failure! Decryption succeeded despite modified authentication tag")
	}

	// Reject modified sequence number (AAD mismatch)
	_, err = separateSession.Decrypt(DirClientToHost, dartGeneratedCiphertextHex, seqNum+999, timestamp)
	if err == nil {
		t.Errorf("Security failure! Decryption succeeded despite modified sequence number in AAD")
	}

	// Reject modified timestamp (AAD mismatch)
	_, err = separateSession.Decrypt(DirClientToHost, dartGeneratedCiphertextHex, seqNum+4, timestamp+5000)
	if err == nil {
		t.Errorf("Security failure! Decryption succeeded despite modified timestamp in AAD")
	}

	// 6. Verify Host->Client Go-generated vector against Dart's expected ciphertext
	hostBlock, _ := aes.NewCipher(hKey)
	hostGcm, _ := cipher.NewGCM(hostBlock)
	hostNonceBytes, _ := hex.DecodeString("1112131415161718191a1b1c")
	hostSealed := hostGcm.Seal(nil, hostNonceBytes, []byte(hostExpectedPlaintext), aad)
	expectedFullHostPayload := append(hostNonceBytes, hostSealed...)
	if hex.EncodeToString(expectedFullHostPayload) != goGeneratedCiphertextHex {
		t.Errorf("Go generated host ciphertext differs from shared vector specification")
	}
}

func TestE2ESession_ReplayAttackRejection(t *testing.T) {
	session, err := NewE2ESession("sess-200", "device-phone-01", "shared-master-secret-32-bytes", 1*time.Hour)
	if err != nil {
		t.Fatalf("Failed to initialize E2E session: %v", err)
	}

	plain := []byte("Run Gradle Build")
	seqNum := int64(10)
	ts := time.Now().UnixNano()

	cipherHex, _ := session.Encrypt(DirClientToHost, plain, seqNum, ts)

	_, err = session.Decrypt(DirClientToHost, cipherHex, seqNum, ts)
	if err != nil {
		t.Fatalf("First decryption failed: %v", err)
	}

	_, err = session.Decrypt(DirClientToHost, cipherHex, seqNum, ts)
	if err != ErrReplayedFrame {
		t.Errorf("Expected ErrReplayedFrame for replayed sequence number, got: %v", err)
	}
}

func TestE2ESession_AADMetadataTamperRejection(t *testing.T) {
	session, err := NewE2ESession("sess-300", "device-phone-01", "shared-master-secret-32-bytes", 1*time.Hour)
	if err != nil {
		t.Fatalf("Failed to initialize E2E session: %v", err)
	}

	plain := []byte("ReadFile(app/build.gradle)")
	seqNum := int64(1)
	ts := time.Now().UnixNano()

	cipherHex, _ := session.Encrypt(DirClientToHost, plain, seqNum, ts)

	tamperedTs := ts + 1000
	_, err = session.Decrypt(DirClientToHost, cipherHex, seqNum, tamperedTs)
	if err == nil {
		t.Errorf("Security flaw! Decryption succeeded despite modified AAD metadata")
	}
}

func TestE2ESession_ExpiredKeyDestruction(t *testing.T) {
	session, err := NewE2ESession("sess-400", "device-phone-01", "shared-master-secret-32-bytes", -1*time.Second)
	if err != nil {
		t.Fatalf("Failed to create session: %v", err)
	}

	_, err = session.Encrypt(DirClientToHost, []byte("test"), 1, time.Now().UnixNano())
	if err != ErrExpiredSessionKey {
		t.Errorf("Expected ErrExpiredSessionKey for expired key, got: %v", err)
	}

	session.Destroy()
	for _, b := range session.ClientToHostKey {
		if b != 0 {
			t.Errorf("Expected ClientToHostKey memory bytes to be zeroed out")
		}
	}
}

func TestE2ESession_SequencePruningAndFailureRollback(t *testing.T) {
	session, err := NewE2ESession("sess-500", "device-phone-01", "shared-master-secret-32-bytes", 1*time.Hour)
	if err != nil {
		t.Fatalf("Failed to create session: %v", err)
	}

	// Test 1: Failed decryption rolls back sequence number so it can be retried
	invalidCipherHex := "00112233445566778899aabbccddeeff00112233445566778899aabb"
	_, err = session.Decrypt(DirClientToHost, invalidCipherHex, 42, time.Now().UnixNano())
	if err == nil {
		t.Errorf("Expected decryption error for invalid ciphertext")
	}

	// Encrypt a valid frame with seqNum 42 and verify decryption succeeds
	plain := []byte("Valid Retry")
	ts := time.Now().UnixNano()
	validCipherHex, _ := session.Encrypt(DirClientToHost, plain, 42, ts)
	decrypted, err := session.Decrypt(DirClientToHost, validCipherHex, 42, ts)
	if err != nil || string(decrypted) != "Valid Retry" {
		t.Fatalf("Failed to decrypt valid retry after failed decryption: %v", err)
	}

	// Test 2: Pruning sequence numbers over 2000 limit
	for seq := int64(43); seq <= 2500; seq++ {
		cHex, _ := session.Encrypt(DirClientToHost, []byte("test"), seq, ts)
		_, _ = session.Decrypt(DirClientToHost, cHex, seq, ts)
	}

	session.mu.Lock()
	seenCount := len(session.seenSeqNums)
	session.mu.Unlock()

	if seenCount > 1500 {
		t.Errorf("Expected seenSeqNums to be pruned below 1500, but count is %d", seenCount)
	}
}
